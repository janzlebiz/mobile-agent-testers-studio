"""Export discovered flows and bug reproductions into runnable Maestro YAML tests."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from mat.findings import discover_persona_dirs, load_all_findings


def _slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:48] or "flow"


def _yaml_str(val: str) -> str:
    escaped = val.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def flow_from_meta(
    app_id: str,
    persona: str,
    meta_files: list[Path],
    title: str = "",
) -> str:
    """Build a Maestro YAML flow from captured screen metadata (.meta.json)."""
    lines = [
        f"# Auto-generated by mobile-agent-testers-studio from persona '{persona}'",
        f"# {title or 'Exploratory walkthrough'}",
        f"appId: {app_id}",
        "---",
        "- launchApp",
    ]
    seen_labels: list[str] = []
    for mf in meta_files:
        try:
            meta = json.loads(mf.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        action = meta.get("last_action")
        if isinstance(action, dict):
            kind = action.get("type")
            if kind == "tap" and action.get("label"):
                lines.append(f"- tapOn: {_yaml_str(str(action['label']))}")
            elif kind == "tap" and action.get("x") is not None and action.get("y") is not None:
                lines.append(f"- tapOn:\n    point: \"{action['x']},{action['y']}\"")
            elif kind == "type" and action.get("text"):
                lines.append(f"- inputText: {_yaml_str(str(action['text']))}")
            elif kind == "scroll":
                lines.append("- scroll")
            elif kind == "back":
                lines.append("- back")
        for el in meta.get("elements", [])[:3]:
            lbl = (el.get("label") or "").strip()
            if lbl and lbl not in seen_labels:
                seen_labels.append(lbl)
                break

    if seen_labels:
        lines.append(f"- assertVisible: {_yaml_str(seen_labels[-1])}")
    return "\n".join(lines) + "\n"


def flow_from_issue(app_id: str, persona: str, issue: dict[str, Any]) -> str:
    """Build a Maestro regression test stub from a structured bug finding."""
    title = issue.get("title") or "Bug regression"
    screen = issue.get("screen") or ""
    steps = issue.get("steps") or ""
    lines = [
        f"# Regression test for [{issue.get('severity', 'major').upper()}] {title}",
        f"# Found by persona: {persona} on screen: {screen or 'unknown'}",
        f"appId: {app_id}",
        "---",
        "- launchApp",
    ]
    if steps:
        for step_line in steps.splitlines():
            clean = step_line.strip().lstrip("0123456789.-) ")
            if clean:
                lines.append(f"# Step: {clean}")
    if screen:
        lines.append(f"- assertVisible: {_yaml_str(screen)}")
    lines.append("# TODO: refine selector assertions below to lock in regression")
    return "\n".join(lines) + "\n"


def export_maestro_suite(
    run_dir: str | Path,
    out_dir: str | Path,
    app_id: str = "com.example.app",
) -> list[Path]:
    """Export Maestro YAML files for all personas & major/blocker issues in a run."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    findings = load_all_findings(run_dir)
    for persona, pdir in discover_persona_dirs(run_dir):
        meta_files = sorted(pdir.glob("*.meta.json"))
        if meta_files:
            target = out / f"walkthrough-{_slug(persona)}.yaml"
            target.write_text(flow_from_meta(app_id, persona, meta_files), encoding="utf-8")
            written.append(target)

        pdata = findings.get(persona, {})
        for idx, issue in enumerate(pdata.get("issues", []), 1):
            if issue.get("severity") in ("blocker", "major"):
                slug = _slug(issue.get("title", f"issue-{idx}"))
                target = out / f"regression-{_slug(persona)}-{idx:02d}-{slug}.yaml"
                target.write_text(flow_from_issue(app_id, persona, issue), encoding="utf-8")
                written.append(target)
    return written
